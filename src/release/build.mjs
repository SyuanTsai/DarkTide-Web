import { canonicalize, computeReleaseId } from './manifest.mjs';
import { validateReleaseCandidate } from '../content/release-candidate.mjs';
import { loadGitSourceBytes } from '../content/git-source.mjs';
import { renderReleaseSite } from '../site/render.mjs';

const outputPath = /^(?:[a-zA-Z0-9_-]+\/)*[a-zA-Z0-9_-]+\.(?:html|css|js|svg|png|webp)$/;
const contentTypes = {
  html: 'text/html; charset=utf-8', css: 'text/css; charset=utf-8',
  js: 'text/javascript; charset=utf-8', svg: 'image/svg+xml',
  png: 'image/png', webp: 'image/webp'
};
const encoder = new TextEncoder();

function bytesOf(value, label) {
  if (typeof value === 'string') return encoder.encode(value);
  if (value instanceof Uint8Array) return new Uint8Array(value);
  throw new Error(`${label} must be a string or Uint8Array`);
}

async function digest(bytes) {
  const hash = await crypto.subtle.digest('SHA-256', bytes);
  return [...new Uint8Array(hash)].map(part => part.toString(16).padStart(2, '0')).join('');
}

function sortedSnapshot(records, key, label) {
  if (!Array.isArray(records) || records.length === 0) throw new Error(`${label} snapshot is missing`);
  const snapshot = structuredClone(records);
  snapshot.sort((a, b) => String(a?.[key]) < String(b?.[key]) ? -1 : String(a?.[key]) > String(b?.[key]) ? 1 : 0);
  const ids = snapshot.map(record => record?.[key]);
  if (ids.some(id => typeof id !== 'string' || !/^[a-z][a-z0-9._-]{0,127}$/.test(id)) ||
      new Set(ids).size !== ids.length) throw new Error(`duplicate or invalid ${label} ID`);
  return snapshot;
}

// This is an inventory of actual output bytes, not an approval to deploy them.
// Final validation must be generated by the full release pipeline.
export async function createReleaseDraft({ files, workerBytes, sourceLocks, rightsLedger,
  taxonomySha256, fieldRequirementSha256, toolCommitSha } = {}) {
  if (![taxonomySha256, fieldRequirementSha256].every(value => typeof value === 'string' && /^[a-f0-9]{64}$/.test(value)) ||
      typeof toolCommitSha !== 'string' || !/^[a-f0-9]{40}$/.test(toolCommitSha)) {
    throw new Error('invalid release hash or tool commit SHA');
  }
  if (!(files instanceof Map) || files.size === 0 || !files.has('index.html')) {
    throw new Error('release output must include index.html');
  }
  const fileSnapshots = [...files].map(([path, content]) => {
    if (typeof path !== 'string' || !outputPath.test(path) || path === 'build-manifest.json') {
      throw new Error(`invalid release output path: ${path}`);
    }
    return [path, bytesOf(content, `file ${path}`)];
  }).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
  const workerSnapshot = bytesOf(workerBytes, 'Worker bundle');
  const sourceSnapshot = sortedSnapshot(sourceLocks, 'source_id', 'source');
  const rightsSnapshot = sortedSnapshot(rightsLedger, 'rights_id', 'rights');
  const entries = [];
  let totalBytes = 0;
  for (const [path, bytes] of fileSnapshots) {
    totalBytes += bytes.byteLength;
    if (!Number.isSafeInteger(totalBytes)) throw new Error('release total bytes overflow');
    const extension = path.split('.').at(-1);
    entries.push({ path, raw_bytes: bytes.byteLength, sha256: await digest(bytes),
      content_type: contentTypes[extension] });
  }
  const manifest = {
    schema_version: 1,
    package_kind: 'release',
    release_id: null,
    source_lock_ids: sourceSnapshot.map(record => record.source_id),
    source_lock_digest: await digest(encoder.encode(canonicalize(sourceSnapshot))),
    rights_ledger_digest: await digest(encoder.encode(canonicalize(rightsSnapshot))),
    taxonomy_sha256: taxonomySha256,
    field_requirement_sha256: fieldRequirementSha256,
    tool_commit_sha: toolCommitSha,
    files: entries,
    worker: { path: 'worker/index.mjs', raw_bytes: workerSnapshot.byteLength,
      sha256: await digest(workerSnapshot) },
    totals: { file_count: entries.length, raw_bytes: totalBytes },
    validation: { complete: false, checks: [] }
  };
  manifest.release_id = await computeReleaseId(manifest);
  return manifest;
}

export async function createValidatedReleaseDraft(data, context, { workerBytes, toolCommitSha } = {}) {
  const stableData = structuredClone(data);
  const stableContext = structuredClone(context);
  const { source_lock_ids: sourceIds, rights_ids: rightsIds } =
    await validateReleaseCandidate(stableData, stableContext);
  const files = await renderReleaseSite(stableData, stableContext);
  const sourceIdSet = new Set(sourceIds);
  const rightsIdSet = new Set(rightsIds);
  const manifest = await createReleaseDraft({
    files, workerBytes,
    sourceLocks: stableContext.sourceLocks.filter(row => sourceIdSet.has(row.source_id)),
    rightsLedger: stableContext.rightsLedger.filter(row => rightsIdSet.has(row.rights_id)),
    taxonomySha256: stableData.taxonomy_sha256,
    fieldRequirementSha256: stableData.field_requirement_sha256,
    toolCommitSha
  });
  return { files, manifest };
}

export async function createGitVerifiedReleaseDraft(data, context,
  { gitCheckouts, workerBytes, toolCommitSha } = {}) {
  const stableData = structuredClone(data);
  const stableContext = structuredClone(context);
  const gitBytes = await loadGitSourceBytes(stableContext.sourceLocks, gitCheckouts);
  if (!(stableContext.sourceBytes instanceof Map)) stableContext.sourceBytes = new Map();
  for (const [sourceId, bytes] of gitBytes) stableContext.sourceBytes.set(sourceId, bytes);
  return createValidatedReleaseDraft(stableData, stableContext, { workerBytes, toolCommitSha });
}
